#!/usr/bin/env python3
"""Generate the NFC composition table of clip_tokenizer_metal.kotoba.in: a supported lower-case letter followed by one combining mark (U+0300 to U+036F,
U+3099, U+309A) composes (unicodedata.normalize("NFC")) into one supported letter. Entries are base << 28 | mark << 14 | composed.
  python3 gen_nfc_table.py > nfc_table.kotoba"""
import unicodedata as u, sys
sys.path.insert(0, ".")
import gen_script_tables as g   # noqa: E402  (class of the script ranges; prints nothing on import)
def old_supported(c):
    return (0xC0 <= c <= 0xFF and c not in (0xD7, 0xF7)) or (0x100 <= c <= 0x17F and c != 0x130) or (0x3041 <= c <= 0x30FF)
def new_supported(c):
    return any(a <= c <= b for a, b in g.RANGES) and g.cls(c) == 1
def supported(c): return old_supported(c) or new_supported(c)
bases = [c for c in list(range(97, 123)) + list(range(0xE0, 0x180)) + list(range(0x3041, 0x3100)) + [c for a, b in g.RANGES for c in range(a, b + 1)]
         if chr(c).lower() == chr(c) and (97 <= c <= 122 or supported(c))]
marks = list(range(0x300, 0x370)) + [0x3099, 0x309A]
ent = []
for b in bases:
    for m in marks:
        n = u.normalize("NFC", chr(b) + chr(m))
        if len(n) == 1 and supported(ord(n)): ent.append((b << 28) | (m << 14) | ord(n))
ent = sorted(set(ent))
chunks = [ent[i:i + 60] for i in range(0, len(ent), 60)]
out = ";; NFC for a letter followed by one combining mark: entries base << 28 | mark << 14 | composed, generated by gen_nfc_table.py (%d entries)\n" % len(ent)
for i, c in enumerate(chunks):
    out += "(defn- nfc-t%d [] :vector-i64\n  (vector-i64 %s))\n" % (i, " ".join(map(str, c)))
out += "(defn- nfc-scan [T :vector-i64 key :i64] :i64\n  (loop [i 0]\n    (if (= i (vector-count T)) -1\n      (let [e (vector-at T i)]\n        (if (= (i64-shift-right e 14) key) (bit-and e 16383) (recur (+ i 1)))))))\n"
out += ";; the composed code point of base + mark, or -1\n(defn- nfc-find [base :i64 mark :i64] :i64\n  (let [key (+ (* base 16384) mark)\n        r0 (nfc-scan (nfc-t0) key)]\n"
for i in range(1, len(chunks)):
    out += "    (if (>= r%d 0) r%d\n      (let [r%d (nfc-scan (nfc-t%d) key)]\n" % (i - 1, i - 1, i, i)
out += "        r%d" % (len(chunks) - 1) + ")" * (2 * (len(chunks) - 1)) + "))\n"
sys.stdout.write(out); sys.stderr.write("%d entries, %d tables\n" % (len(ent), len(chunks)))
