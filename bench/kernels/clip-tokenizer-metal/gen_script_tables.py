#!/usr/bin/env python3
"""Generate the Kotoba tables for the alphabetic scripts beyond Latin (Greek, Cyrillic, Armenian, Hebrew letters): the class of every code point (the
way the oracle's pre-tokenizer sees it) and the lower-casing rule, from Python's unicodedata, as packed integers for clip_tokenizer_metal.kotoba.in.
A code point the program must not guess about is class 4 (refused): marks, anything NFC changes, anything whose lower-case is not one code point
or depends on its neighbours (the capital sigma), unassigned code points.
  python3 gen_script_tables.py > script_tables.kotoba"""
import unicodedata as u, sys
RANGES = [(0x370, 0x52F), (0x531, 0x58A), (0x5D0, 0x5EA)]   # Greek and Coptic, Cyrillic and its supplement, Armenian, Hebrew letters
def cls(c):
    ch = chr(c)
    cat = u.category(ch)
    if cat in ("Mn", "Mc", "Me", "Cn", "Co", "Cs"): return 4
    if u.normalize("NFC", ch) != ch: return 4
    if c == 0x3A3: return 4                                   # capital sigma lower-cases to sigma or final sigma by context
    lo = ch.lower()
    if len(lo) != 1: return 4
    if len(ch.upper()) != 1 and cat.startswith("L") and ch.isupper(): return 4
    if cat.startswith("L"): return 1
    if cat.startswith("N"): return 2
    if ch.isspace() or cat == "Zs": return 0
    return 3
# class runs over the ranges
runs = []
for a, b in RANGES:
    c = a
    while c <= b:
        k = cls(c); e = c
        while e + 1 <= b and cls(e + 1) == k: e += 1
        runs.append((c, e, k)); c = e + 1
cls_packed = [(lo << 20) | (hi << 4) | k for lo, hi, k in runs]
# lower-case runs: constant delta (mode 1), or alternating (mode 2: even offset from lo is upper, +1; mode 3: odd offset)
low = {}
for a, b in RANGES:
    for c in range(a, b + 1):
        if cls(c) == 1 and chr(c).lower() != chr(c): low[c] = ord(chr(c).lower()) - c
cs = sorted(low); lruns = []; i = 0
while i < len(cs):
    c = cs[i]; d = low[c]
    j = i
    while j + 1 < len(cs) and cs[j + 1] == cs[j] + 1 and low[cs[j + 1]] == d: j += 1
    if j > i or d != 1:
        lruns.append((c, cs[j], 1, d)); i = j + 1; continue
    # delta 1 singleton or alternating: extend while cs steps by 2 with delta 1
    j = i
    while j + 1 < len(cs) and cs[j + 1] == cs[j] + 2 and low[cs[j + 1]] == 1: j += 1
    if j > i: lruns.append((c, cs[j], 2, 1))                 # every other code point from c, +1
    else: lruns.append((c, c, 1, 1))
    i = j + 1
low_packed = [(lo << 29) | (hi << 13) | (mode << 9) | (d + 256) for lo, hi, mode, d in lruns]   # delta stored with an offset of 256 (some are negative)
def emit(name, vals, size=60):
    out = ""
    for n in range(0, len(vals), size):
        out += "(defn- %s%d [] :vector-i64\n  (vector-i64 %s))\n" % (name, n // size, " ".join(map(str, vals[n:n + size])))
    return out, (len(vals) + size - 1) // size
if __name__ == "__main__":
  sys.stdout.write(";; generated by gen_script_tables.py (%d class runs, %d lower-case runs)\n" % (len(cls_packed), len(low_packed)))
  for name, vals in (("scls-t", cls_packed), ("slow-t", low_packed)):
    txt, n = emit(name, vals); sys.stdout.write(txt); sys.stderr.write("%s: %d values, %d tables\n" % (name, len(vals), n))
